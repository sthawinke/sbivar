test_that("Cauchy combination rule works as expected", {
  pVals <- runif(20, 0, 1)
  cctP <- CCT(pVals)
  expect_type(cctP, "double")
  expect_lte(cctP, 1)
  expect_gte(cctP, 0)
  expect_type(c(cctP, 1e-20), "double")
  expect_equal(CCT(c(NA, 0.1, 0.2)), NA)
  expect_equal(CCT(c(0, 0.1, 0.2)), 0)
})
